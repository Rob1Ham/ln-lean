#!/usr/bin/env python3
"""Exact source-level checker for the Lean obligation catalog.

The catalog in ``LnLean/Proofs/Obligations.lean`` stores ``leanTarget`` as a
plain ``String``.  Lean therefore cannot tell us whether a target names a real
declaration.  This script supplies that missing check without needing a Lean
environment:

* parse every catalog row (id, leanTarget, status);
* walk ``LnLean/**/*.lean`` and build an exact fully-qualified declaration map,
  tracking ``namespace`` / ``section`` blocks;
* strip comments and string literals before looking for real ``sorry`` terms;
* by default, require every target to resolve exactly (stale / missing /
  ambiguous names are errors);
* with ``--allow-planned``, tolerate an unresolved target only on a
  ``statementOnly`` row.  Such a target is printed as ``PLANNED`` and counted
  separately; it is never treated as proved.  Every other failure remains an
  error, including any unresolved target on a ``proved`` row;
* require every declaration named by a ``proved`` row to exist and, when it is
  a theorem/lemma, to have no ``sorry`` in its source body.

The default is the strict mode required by ``agents/reports/K01.md``.
``--allow-planned`` is an explicitly opt-in acknowledgement that the catalog
tracks future declarations; it does not promote, rewrite, or otherwise accept
them as proved.  Ambiguous targets, duplicate ids, incomplete rows, a wrong row
count, and every failing ``proved`` row still fail in both modes.

The check is deliberately source-level.  It is not a kernel environment query:
it cannot see imported declarations that are absent from this tree, declaration
renames performed by Lean, or lemmas generated by macros.  Those limitations are
reported in ``agents/reports/K01.md``.

Exit status is nonzero if the catalog has a duplicate id, an incomplete row,
the wrong number of rows, an unresolved/ambiguous target that the selected mode
does not permit, or a failing ``proved`` row.  Audit mode additionally prints
promotion candidates (``statementOnly`` rows whose exact targets are sorry-free
theorems/lemmas); it never edits the catalog.  ``--self-test`` runs both modes
and checks their exit codes and planned-target reporting.
"""
from __future__ import annotations

import argparse
import pathlib
import re
import sys
from dataclasses import dataclass, field

ROOT = pathlib.Path(__file__).resolve().parents[1]
CATALOG = ROOT / "LnLean" / "Proofs" / "Obligations.lean"
SOURCE_ROOT = ROOT / "LnLean"
EXPECTED_ROWS = 48

# ---------------------------------------------------------------------------
# Comment / string stripping
# ---------------------------------------------------------------------------


def strip_lean(text: str, keep_strings: bool = True) -> str:
    """Remove Lean comments while preserving offsets and line breaks.

    Nested ``/- ... -/`` comments and ``--`` line comments are removed.  When
    ``keep_strings`` is false the *contents* of string literals are blanked as
    well, so that words such as ``sorry`` inside a string are not mistaken for
    a term.  Quotes and escape handling are preserved either way.

    Non-newline characters in removed regions become spaces, so character
    offsets and line numbers in the result match the original text.
    """
    out: list[str] = []
    i = 0
    n = len(text)
    depth = 0
    in_string = False
    while i < n:
        ch = text[i]
        if depth > 0:
            if text.startswith("/-", i):
                depth += 1
                out.append("  ")
                i += 2
            elif text.startswith("-/", i):
                depth -= 1
                out.append("  ")
                i += 2
            else:
                out.append("\n" if ch == "\n" else " ")
                i += 1
            continue
        if in_string:
            if ch == "\\":
                if i + 1 < n:
                    out.append(ch if keep_strings else " ")
                    out.append(text[i + 1] if keep_strings else ("\n" if text[i + 1] == "\n" else " "))
                    i += 2
                else:
                    out.append(" ")
                    i += 1
            elif ch == '"':
                in_string = False
                out.append('"')
                i += 1
            else:
                out.append(ch if keep_strings else ("\n" if ch == "\n" else " "))
                i += 1
            continue
        if text.startswith("/-", i):
            depth = 1
            out.append("  ")
            i += 2
            continue
        if text.startswith("--", i):
            j = text.find("\n", i)
            if j == -1:
                out.append(" " * (n - i))
                i = n
            else:
                out.append(" " * (j - i))
                out.append("\n")
                i = j + 1
            continue
        if ch == '"':
            in_string = True
            out.append('"')
            i += 1
            continue
        out.append(ch)
        i += 1
    return "".join(out)


# ---------------------------------------------------------------------------
# Catalog parsing
# ---------------------------------------------------------------------------


@dataclass
class CatalogRow:
    id: str
    lean_target: str
    status: str
    line: int
    fields: dict[str, str] = field(default_factory=dict)


def balanced_records(text: str):
    """Yield ``(start, end, body)`` for top-level brace records in *text*."""
    i = 0
    n = len(text)
    in_string = False
    while i < n:
        ch = text[i]
        if in_string:
            if ch == "\\":
                i += 2
            elif ch == '"':
                in_string = False
                i += 1
            else:
                i += 1
            continue
        if ch == '"':
            in_string = True
            i += 1
            continue
        if ch == "{":
            start = i
            depth = 0
            j = i
            in_str = False
            while j < n:
                c = text[j]
                if in_str:
                    if c == "\\":
                        j += 2
                        continue
                    if c == '"':
                        in_str = False
                    j += 1
                    continue
                if c == '"':
                    in_str = True
                    j += 1
                    continue
                if c == "{":
                    depth += 1
                elif c == "}":
                    depth -= 1
                    if depth == 0:
                        yield start, j + 1, text[start + 1 : j]
                        i = j + 1
                        break
                j += 1
            else:
                return
            continue
        i += 1


def parse_catalog(text: str) -> list[CatalogRow]:
    code = strip_lean(text, keep_strings=True)
    rows: list[CatalogRow] = []
    for start, _end, body in balanced_records(code):
        if not re.search(r'\bid\s*:=', body):
            continue
        fields: dict[str, str] = {}
        for m in re.finditer(r'\b(id|claim|leanTarget|status|boltdoc|rlAnchor)\s*:=\s*', body):
            name = m.group(1)
            rest = body[m.end() :]
            if name == "status":
                sm = re.match(r'\.([A-Za-z0-9_]+)', rest)
                fields[name] = sm.group(1) if sm else ""
            else:
                sm = re.match(r'"((?:[^"\\]|\\.)*)"', rest)
                fields[name] = sm.group(1) if sm else ""
        if "id" not in fields:
            continue
        line = code.count("\n", 0, start) + 1
        rows.append(
            CatalogRow(
                id=fields.get("id", ""),
                lean_target=fields.get("leanTarget", ""),
                status=fields.get("status", ""),
                line=line,
                fields=fields,
            )
        )
    return rows


# ---------------------------------------------------------------------------
# Declaration map
# ---------------------------------------------------------------------------

DECL_KINDS = (
    "theorem",
    "lemma",
    "def",
    "abbrev",
    "structure",
    "inductive",
    "class",
    "opaque",
    "axiom",
    "constant",
    "instance",
)
DECL_KIND_RE = re.compile("|".join(DECL_KINDS))
MODIFIERS = ("private", "protected", "noncomputable", "partial", "unsafe", "local", "scoped")
# Lean identifiers in this tree also use `?` and `!` (for example
# `getElem?_append`), so the common `[A-Za-z0-9_'.]` class is not enough.
NAME = r"[A-Za-z0-9_'.?!]+"
NAMESPACE_RE = re.compile(r"^\s*namespace\s+(" + NAME + r")\s*$")
SECTION_RE = re.compile(r"^\s*(?:noncomputable\s+)?section(?:\s+" + NAME + r")?\s*$")
MUTUAL_RE = re.compile(r"^\s*mutual\s*$")
END_RE = re.compile(r"^\s*end(?:\s+" + NAME + r")?\s*$")
SORRY_RE = re.compile(r"\bsorry\b")


@dataclass
class Declaration:
    name: str
    kind: str
    module: str
    file: str
    line: int
    body: str
    has_sorry: bool


def strip_leading_attributes(line: str) -> str:
    """Remove one or more single-line ``@[...]`` attribute blocks."""
    while True:
        m = re.match(r"^\s*@\[", line)
        if not m:
            return line
        depth = 0
        i = m.end() - 1
        while i < len(line):
            if line[i] == "[":
                depth += 1
            elif line[i] == "]":
                depth -= 1
                if depth == 0:
                    break
            i += 1
        if i >= len(line):
            return ""
        line = line[i + 1 :]


def declaration_on_line(line: str):
    """Return ``(kind, name, is_private)`` for a named declaration line."""
    line = strip_leading_attributes(line)
    is_private = False
    while True:
        m = re.match(r"^\s*(" + "|".join(MODIFIERS) + r")\b\s*", line)
        if not m:
            break
        if m.group(1) == "private":
            is_private = True
        line = line[m.end() :]
    m = re.match(r"^\s*(?:(?P<attrs>@\[[^\]]*\])\s*)*", line)
    if m and m.end() > 0:
        line = line[m.end() :]
    m = re.match(
        r"^\s*(?P<kind>" + DECL_KIND_RE.pattern + r")\b"
        r"(?:\s+(?P<name>" + NAME + r"))?",
        line,
    )
    if not m:
        return None
    kind = m.group("kind")
    name = m.group("name")
    if name is None:
        return None
    # Skip declarations whose apparent "name" is actually syntax (anonymous
    # instances, `instance : ...`, etc.).
    if name in ("where", "in", "at", "with"):
        return None
    return kind, name, is_private


def full_name(namespace_parts: list[str], name: str) -> str:
    if name.startswith("_root_."):
        return name[len("_root_.") :]
    ns = ".".join(namespace_parts)
    if ns and not name.startswith(ns + "."):
        return ns + "." + name
    return name


def build_declaration_map() -> tuple[dict[str, list[Declaration]], list[str]]:
    decls: dict[str, list[Declaration]] = {}
    warnings: list[str] = []
    files = sorted(SOURCE_ROOT.rglob("*.lean"))
    for path in files:
        raw = path.read_text(encoding="utf-8")
        # Blank string contents as well as comments: a declaration-looking line
        # inside a multiline string must never enter the declaration map.
        code = strip_lean(raw, keep_strings=False)
        lines = code.splitlines(keepends=True)
        rel = str(path.relative_to(ROOT))
        module = rel[:-5].replace("/", ".")
        namespace: list[str] = []
        block_stack: list[tuple[str, int]] = []
        offsets: list[int] = []
        pos = 0
        for line in lines:
            offsets.append(pos)
            pos += len(line)
        # (start offset, line index, kind, simple name, namespace snapshot,
        #  is_private)
        starts: list[tuple[int, int, str, str, tuple[str, ...], bool]] = []
        for idx, line in enumerate(lines):
            nm = NAMESPACE_RE.match(line)
            if nm:
                parts = nm.group(1).split(".")
                namespace.extend(parts)
                block_stack.append(("namespace", len(parts)))
                continue
            if SECTION_RE.match(line):
                block_stack.append(("section", 0))
                continue
            if MUTUAL_RE.match(line):
                block_stack.append(("mutual", 0))
                continue
            if END_RE.match(line):
                if block_stack:
                    _kind, count = block_stack.pop()
                    if count:
                        del namespace[-count:]
                continue
            dec = declaration_on_line(line)
            if dec:
                kind, name, is_private = dec
                starts.append(
                    (offsets[idx], idx, kind, name, tuple(namespace), is_private)
                )
        for k, (offset, idx, kind, name, ns_snapshot, is_private) in enumerate(starts):
            end = starts[k + 1][0] if k + 1 < len(starts) else len(code)
            body = code[offset:end]
            has_sorry = bool(SORRY_RE.search(body))
            # Lean mangles private names (`_private...`), so a source-level
            # target using the plain name is not an exact declaration.
            if is_private:
                continue
            full = full_name(list(ns_snapshot), name)
            decls.setdefault(full, []).append(
                Declaration(
                    name=full,
                    kind=kind,
                    module=module,
                    file=rel,
                    line=idx + 1,
                    body=body,
                    has_sorry=has_sorry,
                )
            )
        if block_stack:
            warnings.append(f"{rel}: unclosed namespace/section block(s): {block_stack}")
    return decls, warnings


# ---------------------------------------------------------------------------
# Checks and report
# ---------------------------------------------------------------------------


@dataclass
class TargetResult:
    target: str
    decls: list[Declaration]
    error: str = ""


def targets_of(row: CatalogRow) -> list[str]:
    return [t.strip() for t in row.lean_target.split(";") if t.strip()]


def resolve_target(target: str, decls: dict[str, list[Declaration]]) -> TargetResult:
    found = decls.get(target, [])
    if not found:
        return TargetResult(target, [], "unresolved")
    if len(found) > 1:
        modules = ", ".join(f"{d.module}:{d.line}" for d in found)
        return TargetResult(target, found, f"ambiguous declaration ({modules})")
    return TargetResult(target, found)


def short_name(name: str) -> str:
    return name.rsplit(".", 1)[-1]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--audit",
        action="store_true",
        help="print promotion candidates (the default behavior)",
    )
    parser.add_argument(
        "--no-candidates",
        action="store_true",
        help="omit the statementOnly promotion-candidate table",
    )
    parser.add_argument(
        "--allow-planned",
        action="store_true",
        help=(
            "permit unresolved targets on statementOnly rows, reported as PLANNED "
            "instead of errors; proved rows and all other checks stay strict"
        ),
    )
    parser.add_argument(
        "--self-test",
        action="store_true",
        help=(
            "run the checker in strict and --allow-planned modes and verify both "
            "exit codes and the PLANNED reporting"
        ),
    )
    args = parser.parse_args(argv)

    if args.self_test:
        return self_test()

    if not CATALOG.exists():
        print(f"error: catalog not found: {CATALOG}", file=sys.stderr)
        return 2
    if not SOURCE_ROOT.exists():
        print(f"error: source root not found: {SOURCE_ROOT}", file=sys.stderr)
        return 2

    rows = parse_catalog(CATALOG.read_text(encoding="utf-8"))
    decls, warnings = build_declaration_map()
    by_short: dict[str, list[str]] = {}
    for name in decls:
        by_short.setdefault(short_name(name), []).append(name)

    errors: list[str] = []
    ids: list[str] = []
    for row in rows:
        ids.append(row.id)
        if not row.id or not row.lean_target or not row.status:
            errors.append(f"{row.id or '<missing id>'} (line {row.line}): incomplete catalog row")

    duplicates = sorted({i for i in ids if i and ids.count(i) > 1})
    for dup in duplicates:
        errors.append(f"duplicate catalog id: {dup}")
    if len(rows) != EXPECTED_ROWS:
        errors.append(f"catalog has {len(rows)} rows, expected {EXPECTED_ROWS}")

    # Report table: one line per target so semicolon-separated rows are visible.
    header = (
        f"{'ID':<11} {'STATUS':<14} {'KIND':<10} {'SORRY':<6} "
        f"{'MODULE':<34} TARGET"
    )
    print(header)
    print("-" * len(header))

    results: list[tuple[CatalogRow, TargetResult]] = []
    planned: list[tuple[CatalogRow, TargetResult]] = []
    unresolved = 0
    proved_failures = 0
    for row in rows:
        targets = targets_of(row)
        if not targets:
            errors.append(f"{row.id}: empty leanTarget")
            proved_failures += 1 if row.status == "proved" else 0
            print(f"{row.id:<11} {row.status:<14} {'-':<10} {'-':<6} {'-':<34} <empty>")
            continue
        for target in targets:
            result = resolve_target(target, decls)
            results.append((row, result))
            if result.error:
                # A missing target is acceptable only as a *declared future*
                # target of a statementOnly row, and only in the explicit
                # opt-in mode.  It is reported as PLANNED and never as proved.
                if (
                    args.allow_planned
                    and result.error == "unresolved"
                    and row.status == "statementOnly"
                ):
                    planned.append((row, result))
                    print(
                        f"{row.id:<11} {row.status:<14} {'-':<10} {'-':<6} "
                        f"{'-':<34} {target}  <PLANNED (no declaration yet)>"
                    )
                    continue
                unresolved += 1
                msg = f"{row.id}: target {target!r} {result.error}"
                if result.error == "unresolved":
                    near = sorted(by_short.get(short_name(target), []))
                    if near:
                        msg += " (same short name in: " + ", ".join(near[:5]) + ")"
                errors.append(msg)
                if row.status == "proved":
                    proved_failures += 1
                print(
                    f"{row.id:<11} {row.status:<14} {'-':<10} {'-':<6} "
                    f"{'-':<34} {target}  <{result.error}>"
                )
                continue
            decl = result.decls[0]
            sorry = "yes" if decl.has_sorry else "no"
            fail = ""
            if row.status == "proved":
                if decl.kind in ("theorem", "lemma") and decl.has_sorry:
                    fail = "  <SORRY IN PROVED ROW>"
                    proved_failures += 1
                    errors.append(
                        f"{row.id}: proved target {target!r} is a {decl.kind} with actual sorry "
                        f"in {decl.module}:{decl.line}"
                    )
                elif decl.kind in ("axiom", "constant", "opaque"):
                    fail = f"  <PROVED TARGET IS {decl.kind.upper()}>"
                    proved_failures += 1
                    errors.append(
                        f"{row.id}: proved target {target!r} is a {decl.kind}, not a theorem/proof "
                        f"({decl.module}:{decl.line})"
                    )
            print(
                f"{row.id:<11} {row.status:<14} {decl.kind:<10} {sorry:<6} "
                f"{decl.module:<34} {target}{fail}"
            )

    # Promotion candidates: every target resolves to a sorry-free theorem/lemma.
    candidates: list[tuple[CatalogRow, list[Declaration]]] = []
    for row in rows:
        if row.status != "statementOnly":
            continue
        targets = targets_of(row)
        resolved = [resolve_target(t, decls) for t in targets]
        if not targets or any(r.error for r in resolved):
            continue
        ds = [r.decls[0] for r in resolved]
        if all(d.kind in ("theorem", "lemma") and not d.has_sorry for d in ds):
            candidates.append((row, ds))

    if not args.no_candidates:
        print()
        print("Promotion candidates (statementOnly, exact target, theorem/lemma, no sorry)")
        print("-" * 88)
        if candidates:
            for row, ds in candidates:
                kinds = ", ".join(f"{d.kind} {d.name} @ {d.module}:{d.line}" for d in ds)
                print(f"{row.id}: {kinds}")
        else:
            print("(none)")

    if args.allow_planned:
        print()
        print("Planned targets (statementOnly, unresolved, permitted by --allow-planned)")
        print("-" * 88)
        if planned:
            for row, result in planned:
                target = result.target
                near = sorted(by_short.get(short_name(target), []))
                extra = ""
                if near:
                    extra = " (same short name in: " + ", ".join(near[:5]) + ")"
                print(f"{row.id}: {target}{extra}")
        else:
            print("(none)")

    print()
    proved_rows = sum(1 for r in rows if r.status == "proved")
    statement_rows = sum(1 for r in rows if r.status == "statementOnly")
    mode = "mode=allow-planned " if args.allow_planned else ""
    planned_part = f"planned={len(planned)} " if args.allow_planned else ""
    print(
        f"summary: {mode}rows={len(rows)} proved={proved_rows} statementOnly={statement_rows} "
        f"targets={len(results)} unresolved={unresolved} {planned_part}"
        f"proved_failures={proved_failures} duplicate_ids={len(duplicates)} "
        f"candidates={len(candidates)} declarations={sum(len(v) for v in decls.values())}"
    )
    for warning in warnings:
        print(f"warning: {warning}", file=sys.stderr)

    if errors:
        print()
        print("ERRORS:")
        for err in errors:
            print(f"  - {err}")
        return 1
    if args.allow_planned:
        print(
            f"OK (--allow-planned): every proved target resolves exactly and every proved row "
            f"is sorry-free; {len(planned)} statementOnly target(s) are PLANNED, not proved."
        )
    else:
        print("OK: every catalog target resolves exactly and every proved row is sorry-free.")
    return 0


def _run_captured(argv: list[str]) -> tuple[int, str]:
    """Run ``main`` with stdout captured, returning ``(rc, output)``."""
    import contextlib
    import io

    buffer = io.StringIO()
    with contextlib.redirect_stdout(buffer):
        rc = main(argv)
    return rc, buffer.getvalue()


def _summary_number(output: str, key: str) -> int:
    match = re.search(rf"\b{re.escape(key)}=(\d+)", output)
    return int(match.group(1)) if match else -1


def self_test() -> int:
    """Check strict and ``--allow-planned`` behavior on the live catalog.

    The test is intentionally about *behavior*, not a frozen catalog: strict
    mode may be clean (RC 0) if every target is resolved, and must be RC 1 when
    the catalog still has unresolved targets.  ``--allow-planned`` must be RC 0
    whenever the only remaining problem is unresolved ``statementOnly`` targets,
    must report them as ``PLANNED``, and must never print ``PLANNED`` in strict
    mode.  Ambiguous targets, desyncs, and failing proved rows still return 1 in
    both modes and make this test fail.
    """
    strict_rc, strict_out = _run_captured(["--audit"])
    allow_rc, allow_out = _run_captured(["--allow-planned", "--audit"])

    strict_unresolved = _summary_number(strict_out, "unresolved")
    strict_failures = _summary_number(strict_out, "proved_failures")
    allow_planned = _summary_number(allow_out, "planned")
    allow_unresolved = _summary_number(allow_out, "unresolved")
    allow_failures = _summary_number(allow_out, "proved_failures")

    print(
        f"self-test: strict RC={strict_rc} (unresolved={strict_unresolved}, "
        f"proved_failures={strict_failures})"
    )
    print(
        f"self-test: --allow-planned RC={allow_rc} (planned={allow_planned}, "
        f"unresolved={allow_unresolved}, proved_failures={allow_failures})"
    )

    problems: list[str] = []
    if strict_unresolved < 0 or allow_planned < 0:
        problems.append("could not read the summary line")
    if strict_rc not in (0, 1) or allow_rc not in (0, 1):
        problems.append("unexpected exit code (input tree missing?)")
    if strict_rc == 1 and strict_out.count("<PLANNED") != 0:
        problems.append("strict mode printed a PLANNED target")
    if strict_rc == 1 and "ERRORS:" not in strict_out:
        problems.append("strict mode returned 1 without an ERRORS section")
    if allow_rc != 0:
        problems.append("--allow-planned did not return 0 on the current catalog")
    if allow_failures != 0:
        problems.append("--allow-planned reported a proved-row failure")
    if allow_unresolved != 0:
        problems.append("--allow-planned counted a permitted target as unresolved")
    if strict_rc == 1:
        if allow_planned != strict_unresolved:
            problems.append(
                "planned count under --allow-planned does not match strict unresolved count"
            )
        if "<PLANNED (no declaration yet)>" not in allow_out:
            problems.append("--allow-planned did not report a PLANNED target")
        if "Planned targets (statementOnly, unresolved" not in allow_out:
            problems.append("--allow-planned did not print the planned-target summary")
        if "Promotion candidates" not in allow_out:
            problems.append("--allow-planned --audit did not print promotion candidates")
        if "OK (--allow-planned)" not in allow_out:
            problems.append("--allow-planned did not print its success line")
    if problems:
        print("self-test: FAIL")
        for problem in problems:
            print(f"  - {problem}")
        return 1
    print("self-test: PASS")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
