#!/usr/bin/env bash
# Regenerate the root module from the actual Lean file tree.
set -euo pipefail
cd "$(dirname "$(readlink -f "$0")")/.."
{
  echo "/-"
  echo "  ln-lean root module.  GENERATED by scripts/regen-root.sh."
  echo "  Do not edit by hand."
  echo "-/"
  find LnLean -name '*.lean' \
    | grep -v '^LnLean/Proofs/All\.lean$' \
    | grep -v '^LnLean/Proofs/PhaseC2\.lean$' \
    | sed 's#^#import #; s#/#.#g; s#\.lean$##' | sort -u
} > LnLean.lean
cat LnLean.lean
